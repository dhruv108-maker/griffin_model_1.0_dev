import {
  CircleDot,
  GitBranch,
  Network,
  Share2,
} from "lucide-react";

function GraphMetric({
  label,
  value,
  icon: Icon,
}) {
  return (
    <div className="griffin-graph-metric">
      <div className="griffin-graph-metric-icon">
        <Icon size={16} />
      </div>

      <div>
        <span>{label}</span>
        <strong>{value ?? "—"}</strong>
      </div>
    </div>
  );
}

function VisualizationPreview({
  title,
  payload,
}) {
  const hasData =
    payload &&
    typeof payload === "object" &&
    Object.keys(payload).length > 0;

  return (
    <div className="griffin-graph-visualization">
      <div className="griffin-graph-visualization-header">
        <span>{title}</span>

        {hasData && (
          <span className="griffin-data-badge">
            DATA
          </span>
        )}
      </div>

      {!hasData ? (
        <div className="griffin-graph-visualization-empty">
          No visualization payload returned.
        </div>
      ) : (
        <div className="griffin-graph-data-preview">
          {Object.entries(payload)
            .slice(0, 8)
            .map(([key, value]) => (
              <div
                key={key}
                className="griffin-graph-data-row"
              >
                <span>{key}</span>

                <strong>
                  {typeof value === "object"
                    ? Array.isArray(value)
                      ? `${value.length} items`
                      : `${Object.keys(value).length} fields`
                    : String(value)}
                </strong>
              </div>
            ))}
        </div>
      )}
    </div>
  );
}

export default function GraphPanel({
  result,
  statistics,
  visualizations,
}) {
  const graph =
    statistics ||
    result?.graph_statistics ||
    {};

  const visuals =
    visualizations ||
    result?.visualizations ||
    {};

  return (
    <section className="griffin-result-section griffin-graph-panel">
      <div className="griffin-result-section-header">
        <div>
          <span className="griffin-eyebrow">
            EVIDENCE GRAPH
          </span>

          <h2>Graph structure</h2>

          <p>
            Structural statistics and visualization
            payloads generated by Griffin.
          </p>
        </div>

        <div className="griffin-result-header-icon">
          <Network size={19} />
        </div>
      </div>

      <div className="griffin-graph-metrics">
        <GraphMetric
          label="Total nodes"
          value={graph.total_nodes}
          icon={CircleDot}
        />

        <GraphMetric
          label="Total edges"
          value={graph.total_edges}
          icon={GitBranch}
        />

        <GraphMetric
          label="Unit nodes"
          value={graph.unit_nodes}
          icon={Network}
        />

        <GraphMetric
          label="Topic nodes"
          value={graph.topic_nodes}
          icon={CircleDot}
        />

        <GraphMetric
          label="Evidence nodes"
          value={graph.evidence_nodes}
          icon={Share2}
        />

        <GraphMetric
          label="Graph density"
          value={graph.graph_density}
          icon={Network}
        />

        <GraphMetric
          label="Average degree"
          value={graph.average_degree}
          icon={GitBranch}
        />
      </div>

      <div className="griffin-graph-visualizations">
        <VisualizationPreview
          title="Unit coverage"
          payload={
            visuals.unit_coverage_bar_chart
          }
        />

        <VisualizationPreview
          title="Topic distribution"
          payload={
            visuals.topic_coverage_pie_chart
          }
        />

        <VisualizationPreview
          title="Page evidence distribution"
          payload={
            visuals.page_evidence_distribution
          }
        />

        <VisualizationPreview
          title="Confidence distribution"
          payload={
            visuals.confidence_histogram
          }
        />

        <VisualizationPreview
          title="Curriculum treemap"
          payload={
            visuals.curriculum_treemap
          }
        />

        <VisualizationPreview
          title="Curriculum sunburst"
          payload={
            visuals.curriculum_sunburst
          }
        />
      </div>
    </section>
  );
}